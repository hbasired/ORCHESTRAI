    """Honest status — the config is generated; the live PQC TLS is Stage 18."""
    return {"hybrid_kem_groups": HYBRID_KEM_GROUPS, "signature": HYBRID_SIGNATURE,
            "live_pqc_tls": False, "stage": "scaffold (Stage 14); live ML-KEM-768 mTLS = Stage 18 (KB_13)",
            "sidecar": "openssl 3.5 + oqs-provider via haproxy/stunnel (docker-compose.pqc.yml)"}


